/**
 * Bundle `src/client` into the single `client.js` the Host serves.
 *
 * The client module system only accepts one bundle per package: `dsh.client`
 * has no multi-entry form, and the lazy `client.<name>.js` chunks are for
 * compiler-generated splits, not hand-written modules. So the source lives in
 * `src/client/` and this script emits the bundle the loader actually runs.
 *
 * The emitted file is the loader call the browser executes at materialization:
 * the bundle body sits inside `factory(require)`, which is what makes the
 * shared module table (React) reach the code while `module.exports` still
 * carries `{ inject, apply }`.
 *
 * Usage: `node build.mjs` (one shot) or `node build.mjs --watch`.
 */
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';

/** Module id the browser registers this bundle under. */
const ID = '@local/dsh-session-admin';

/** Path of the emitted bundle, relative to this script. */
const OUT = new URL('./client.js', import.meta.url);

/** Source entry point, relative to this script. */
const ENTRY = new URL('./src/client/index.js', import.meta.url).pathname;

/**
 * Wrap one bundled body in the Host module loader call.
 * @param body - CJS bundle text.
 * @returns the file contents of `client.js`.
 */
function wrap(body) {
	return `/* Generated by build.mjs from src/client — edit the source, then \`npm run build\`. */
window.__ModuleLoader__.load({
	id: '${ID}',
	factory(require) {
		var module = { exports: {} };
		var exports = module.exports;
${body}
		return module.exports;
	},
});
`;
}

/** Options shared by the one-shot and watch runs. */
const options = {
	entryPoints: [ENTRY],
	bundle: true,
	format: 'cjs',
	platform: 'browser',
	target: 'es2022',
	external: ['react'],
	legalComments: 'none',
	logLevel: 'warning',
	write: false,
	plugins: [
		{
			name: 'session-admin-client-bundle',
			setup(pluginBuild) {
				pluginBuild.onEnd(async (result) => {
					if (result.errors.length > 0) return;
					const body = result.outputFiles[0].text.trimEnd();
					await writeFile(OUT, wrap(body));
					console.log(`session-admin: wrote ${OUT.pathname}`);
				});
			},
		},
	],
};

if (process.argv.includes('--watch')) {
	const { context } = await import('esbuild');
	const running = await context(options);
	await running.watch();
	console.log('session-admin: watching src/client');
} else {
	await build(options);
}
